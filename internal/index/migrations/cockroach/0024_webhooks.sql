-- 0024: webhooks (#77; docs/spec/webhooks.md, docs/spec/index-schema.md, Webhooks). Control
-- plane, backed up, never rebuilt: webhooks holds the URL, the repo mask and the secret
-- encrypted with the master key; webhook_deliveries is the outbox, written in the transaction
-- of each event's audit row, and the delivery log. Expand only (CockroachDB).

CREATE TABLE IF NOT EXISTS webhooks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid         text        NOT NULL,
    mask        text        NOT NULL,
    url         text        NOT NULL,
    events      jsonb,
    secret_enc  bytea       NOT NULL,
    active      boolean     NOT NULL,
    description text        NOT NULL,
    created_by  text        NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS webhooks_uid ON webhooks (uid);

CREATE TABLE IF NOT EXISTS webhook_deliveries (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    webhook_id   bigint      NOT NULL REFERENCES webhooks (id) ON DELETE CASCADE,
    event_id     text        NOT NULL,
    event_type   text        NOT NULL,
    payload      bytea       NOT NULL,
    state        text        NOT NULL,
    attempts     integer     NOT NULL,
    next_at      timestamptz NOT NULL,
    claimed_by   text       ,
    claimed_at   timestamptz,
    last_at      timestamptz,
    last_status  integer,
    last_error   text       ,
    created_at   timestamptz NOT NULL,
    delivered_at timestamptz
);

CREATE INDEX IF NOT EXISTS webhook_deliveries_due ON webhook_deliveries (next_at) WHERE state = 'pending';
CREATE INDEX IF NOT EXISTS webhook_deliveries_hook ON webhook_deliveries (webhook_id, id);
CREATE INDEX IF NOT EXISTS webhook_deliveries_created ON webhook_deliveries (created_at);
