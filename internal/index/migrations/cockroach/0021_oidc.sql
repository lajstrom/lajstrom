-- 0021: OIDC login (#69; docs/spec/rbac.md §8, docs/spec/index-schema.md). identities maps
-- the iss and sub of an ID token to a user; identity_groups holds the groups of its latest
-- login, replaced by each login in the transaction that moves auth_version. oidc_logins holds
-- the login requests of the code flow and the device requests, for ten minutes, so that any
-- replica finishes a flow another started; it keeps hashes of the state, the cookie and the
-- device code, never those secrets (CockroachDB).

CREATE TABLE IF NOT EXISTS identities (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    issuer           text        NOT NULL,
    subject          text        NOT NULL,
    created_at       timestamptz NOT NULL,
    login_at         timestamptz NOT NULL,
    groups_expire_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS identities_subject ON identities (issuer, subject);
CREATE INDEX IF NOT EXISTS identities_user ON identities (user_id);

CREATE TABLE IF NOT EXISTS identity_groups (
    identity_id bigint NOT NULL REFERENCES identities (id) ON DELETE CASCADE,
    name        text   NOT NULL,
    PRIMARY KEY (identity_id, name)
);

CREATE TABLE IF NOT EXISTS oidc_logins (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        text        NOT NULL,
    state       text       ,
    binding     text       ,
    nonce       text       ,
    verifier    text       ,
    device_id   bigint      REFERENCES oidc_logins (id) ON DELETE CASCADE,
    device_code text       ,
    user_code   text       ,
    status      text        NOT NULL,
    user_id     bigint      REFERENCES users (id) ON DELETE CASCADE,
    polled_at   timestamptz,
    created_at  timestamptz NOT NULL,
    expires_at  timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS oidc_logins_state ON oidc_logins (state) WHERE state IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS oidc_logins_device_code ON oidc_logins (device_code) WHERE device_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS oidc_logins_user_code ON oidc_logins (user_code) WHERE user_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS oidc_logins_expires ON oidc_logins (expires_at);
