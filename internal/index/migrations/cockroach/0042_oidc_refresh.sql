-- 0042: asking the IdP again about each OIDC login (#1282; docs/spec/rbac.md §8, Asking the IdP
-- again; docs/spec/index-schema.md, Coordination). oidc_refresh holds a row per OIDC login that
-- keeps a refresh token: the token sealed with the master key, never in clear; the login request
-- until its token is minted, then that token; when the IdP last confirmed the login, when it is
-- due again, and the claim of the replica that refreshes it. Expand only: the binaries before it
-- neither read nor write the table, and refuse auth.oidc.refresh (CockroachDB).

CREATE TABLE IF NOT EXISTS oidc_refresh (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id      bigint,
    token_id      bigint      REFERENCES tokens (id) ON DELETE CASCADE,
    identity_id   bigint      NOT NULL REFERENCES identities (id) ON DELETE CASCADE,
    refresh_enc   bytea       NOT NULL,
    created_at    timestamptz NOT NULL,
    refreshed_at  timestamptz NOT NULL,
    next_at       timestamptz NOT NULL,
    failures      integer     NOT NULL DEFAULT 0,
    claimed_by    text,
    claimed_until timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS oidc_refresh_token ON oidc_refresh (token_id) WHERE token_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS oidc_refresh_login ON oidc_refresh (login_id) WHERE login_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS oidc_refresh_next ON oidc_refresh (next_at);
