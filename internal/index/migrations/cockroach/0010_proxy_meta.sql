-- 0010: proxy repos (ADR 0013; docs/spec/index-schema.md, Proxy and group repos). repos.upstream
-- holds a proxy's settings, NULL on every other kind. proxy_meta is a cache of the upstream's
-- documents, one row per proxy repo, name key and document kind: reindex neither reads nor
-- writes it, and dropping it costs upstream requests and nothing else (CockroachDB).

ALTER TABLE repos ADD COLUMN IF NOT EXISTS upstream jsonb;

CREATE TABLE IF NOT EXISTS proxy_meta (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id       bigint      NOT NULL REFERENCES repos (id) ON DELETE CASCADE,
    name          text        NOT NULL,
    kind          text        NOT NULL,
    state         text        NOT NULL,
    content       bytea,
    content_type  text       ,
    sha256        text       ,
    etag          text       ,
    last_modified text       ,
    checked_at    timestamptz NOT NULL,
    UNIQUE (repo_id, name, kind)
);
