-- 0001: every table of docs/spec/index-schema.md, control plane and derived (CockroachDB).
-- Text columns have no collation: CockroachDB compares strings by their bytes, as SQLite does,
-- and has no collation "C". Ids are identity columns, which draw from a sequence, so that they
-- ascend from 1 as Postgres's bigserial does; CockroachDB's bigserial is unique_rowid(), 64-bit
-- values above 2^53. Timestamps are timestamptz with microsecond precision; json is jsonb.
--
-- Every cockroach migration runs one statement at a time, each in a transaction of its own, and
-- runs again from its first statement when it stopped half-way, so each statement may find its
-- work done (IF NOT EXISTS, ON CONFLICT DO NOTHING; docs/spec/index-schema.md, Migrations).
-- No release migrated a CockroachDB database before 0021, so 0001 to 0021 run on an empty one.

-- Control plane.

CREATE TABLE IF NOT EXISTS repos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    format         text        NOT NULL,
    name           text        NOT NULL,
    registry       text        NOT NULL,
    prefix         text        NOT NULL,
    kind           text        NOT NULL,
    anonymous_read boolean     NOT NULL,
    policy         jsonb,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,
    UNIQUE (format, name)
);

CREATE TABLE IF NOT EXISTS users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL UNIQUE,
    password_hash text       ,
    kind          text        NOT NULL,
    disabled      boolean     NOT NULL,
    created_at    timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS tokens (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         text        NOT NULL,
    user_id      bigint      REFERENCES users (id) ON DELETE CASCADE,
    repo_id      bigint      REFERENCES repos (id) ON DELETE CASCADE,
    name         text        NOT NULL,
    hash         text        NOT NULL UNIQUE,
    scopes       jsonb,
    expires_at   timestamptz,
    last_used_at timestamptz,
    created_at   timestamptz NOT NULL,
    revoked_at   timestamptz
);
CREATE INDEX IF NOT EXISTS tokens_user_id ON tokens (user_id);
CREATE INDEX IF NOT EXISTS tokens_repo_id ON tokens (repo_id);

CREATE TABLE IF NOT EXISTS bindings (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal  text        NOT NULL,
    role       text        NOT NULL,
    repo_mask  text        NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS bindings_principal ON bindings (principal);

CREATE TABLE IF NOT EXISTS keys (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     bigint      REFERENCES repos (id) ON DELETE CASCADE,
    kind        text        NOT NULL,
    public      bytea       NOT NULL,
    private_enc bytea       NOT NULL,
    fingerprint text        NOT NULL,
    created_at  timestamptz NOT NULL,
    retired_at  timestamptz
);
CREATE INDEX IF NOT EXISTS keys_repo_id_kind ON keys (repo_id, kind);

CREATE TABLE IF NOT EXISTS sessions (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id    bigint      NOT NULL REFERENCES repos (id) ON DELETE CASCADE,
    key        text        NOT NULL,
    principal  text        NOT NULL,
    state      text        NOT NULL,
    files      jsonb,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_repo_id_key ON sessions (repo_id, key);

CREATE TABLE IF NOT EXISTS audit (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at        timestamptz NOT NULL,
    principal text        NOT NULL,
    action    text        NOT NULL,
    repo      text        NOT NULL,
    subject   text        NOT NULL,
    digest    text       ,
    ip        text        NOT NULL,
    details   jsonb
);
CREATE INDEX IF NOT EXISTS audit_at ON audit (at);

-- Derived: rebuilt by lajstrom reindex.

CREATE TABLE IF NOT EXISTS packages (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id    bigint      NOT NULL REFERENCES repos (id) ON DELETE CASCADE,
    name       text        NOT NULL,
    name_oci   text        NOT NULL,
    created_at timestamptz NOT NULL,
    UNIQUE (repo_id, name)
);

CREATE TABLE IF NOT EXISTS versions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id    bigint      NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    version       text        NOT NULL,
    variant       text        NOT NULL DEFAULT '',
    tag           text        NOT NULL,
    digest        text        NOT NULL,
    artifact_type text        NOT NULL,
    attrs         jsonb,
    metadata      jsonb,
    created_at    timestamptz NOT NULL,
    indexed_at    timestamptz NOT NULL,
    UNIQUE (package_id, version, variant),
    UNIQUE (package_id, tag)
);
CREATE INDEX IF NOT EXISTS versions_digest ON versions (digest);

CREATE TABLE IF NOT EXISTS files (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id bigint    NOT NULL REFERENCES versions (id) ON DELETE CASCADE,
    name       text      NOT NULL,
    media_type text      NOT NULL,
    digest     text      NOT NULL,
    size       bigint    NOT NULL,
    attrs      jsonb
);
CREATE INDEX IF NOT EXISTS files_version_id_name ON files (version_id, name);
CREATE INDEX IF NOT EXISTS files_name ON files (name);

CREATE TABLE IF NOT EXISTS index_cache (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id     bigint      NOT NULL REFERENCES repos (id) ON DELETE CASCADE,
    scope       text        NOT NULL,
    kind        text        NOT NULL,
    content     bytea       NOT NULL,
    sha256      text        NOT NULL,
    rendered_at timestamptz NOT NULL,
    signed_at   timestamptz,
    UNIQUE (repo_id, scope, kind)
);

CREATE TABLE IF NOT EXISTS oci_repos (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id bigint      NOT NULL REFERENCES repos (id) ON DELETE CASCADE,
    path    text        NOT NULL,
    seen_at timestamptz NOT NULL,
    UNIQUE (repo_id, path)
);
